// ─── Internal helpers ────────────────────────────────────────────────────────

/** Return the configured brand prefix for storage namespacing. Falls
 * back to `proctira` so SSR / tests do not need any env setup.
 */
function getBrand(): string {
  // `process.env` exists in Node and in Webpack-transpiled browser
  // bundles. We avoid `import.meta.env` here so the module remains
  // usable from both vitest and the Next.js runtime.
  if (typeof process !== 'undefined' && process.env) {
    const brand = process.env['NEXT_PUBLIC_BRAND'] ?? 'proctira';
    if (brand && brand.length > 0) return brand;
  }
  return 'proctira';
}

/**
 * Open (or upgrade) the Sync_Queue database. The caller is responsible
 * for closing the connection — we do not cache it because tests open
 * many disposable dbs and a stale handle would point to a deleted db.
 *
 * Throws if `indexedDB` is unavailable so callers can decide whether
 * to surface an error or no-op (e.g. during SSR).
 */
function openDatabase(): Promise<IDBDatabase> {
  if (typeof indexedDB === 'undefined') {
    return Promise.reject(
      new Error('Sync_Queue: indexedDB is not available in this environment'),
    );
  }
  return new Promise<IDBDatabase>((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);

    request.onupgradeneeded = () => {
      const db = request.result;
      if (!db.objectStoreNames.contains(STORE_NAME)) {
        const store = db.createObjectStore(STORE_NAME, { keyPath: 'id' });
        // Indexed so `replayAll` iterates in submission order without
        // pulling every record into memory and sorting.
        store.createIndex(INDEX_CREATED_AT, 'createdAt', { unique: false });
      }
    };

    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error ?? new Error('IndexedDB open failed'));
    request.onblocked = () =>
      reject(new Error('Sync_Queue: open blocked by another connection'));
  });
}

/** Promisify a single IndexedDB request so we can `await` it. */
function awaitRequest<T>(request: IDBRequest<T>): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error ?? new Error('IndexedDB request failed'));
  });
}

/** Promisify a transaction's completion (for write transactions). */
function awaitTransaction(tx: IDBTransaction): Promise<void> {
  return new Promise<void>((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onabort = () => reject(tx.error ?? new Error('IndexedDB transaction aborted'));
    tx.onerror = () => reject(tx.error ?? new Error('IndexedDB transaction failed'));
  });
}

/**
 * Run a callback inside a transaction with the given mode and close
 * the database afterwards. Centralising this keeps the public methods
 * focused on their per-operation logic.
 */
async function withStore<T>(
  mode: IDBTransactionMode,
  fn: (store: IDBObjectStore) => Promise<T> | T,
): Promise<T> {
  const db = await openDatabase();
  try {
    const tx = db.transaction(STORE_NAME, mode);
    const store = tx.objectStore(STORE_NAME);
    const result = await fn(store);
    if (mode !== 'readonly') {
      await awaitTransaction(tx);
    }
    return result;
  } finally {
    db.close();
  }
}

// ─── Public API ──────────────────────────────────────────────────────────────

/**
 * Persist a write operation for later replay. Returns the queue id so
 * the caller can show "Queued" UI and later correlate the replay
 * outcome.
 *
 * `enqueue` does not attempt to send the request — call sites should
 * fall through to `enqueue` only when offline / heartbeat failed.
 */
export async function enqueue(input: EnqueueInput): Promise<string> {
  const id = input.id ?? generateIdempotencyKey();
  const idempotencyKey = input.idempotencyKey ?? generateIdempotencyKey();
  const createdAt = input.createdAt ?? new Date().toISOString();

  const op: SyncQueueOperation = {
    id,
    tenantId: input.tenantId,
    userId: input.userId,
    operationType: input.operationType,
    targetEntity: input.targetEntity,
    targetId: input.targetId ?? '',
    payload: input.payload,
    idempotencyKey,
    createdAt,
    attemptCount: 0,
    lastAttemptAt: null,
    lastError: null,
  };

  await withStore('readwrite', (store) => {
    store.add(op);
  });
  return id;
}

/**
 * Remove a single operation. Intended for the "Discard" action in
 * the Conflict_Resolution dialog (task 54.5) and as the success path
 * inside `replayAll`. Idempotent: deleting a missing id is not an
 * error.
 */
export async function dequeue(id: string): Promise<void> {
  await withStore('readwrite', (store) => {
    store.delete(id);
  });
}

/**
 * Read every queued operation in submission order. Used by the
 * Connectivity_Indicator badge, the sync errors tray, and the
 * conflict dialog.
 */
export async function peekAll(): Promise<SyncQueueOperation[]> {
  return withStore('readonly', async (store) => {
    const index = store.index(INDEX_CREATED_AT);
    const request = index.getAll();
    const all = await awaitRequest(request);
    // `getAll` on an index returns ascending by index key — i.e.
    // submission order. We still defensively re-sort in case a
    // platform returns ties out of order.
    return [...all].sort((a, b) =>
      a.createdAt === b.createdAt
        ? a.id.localeCompare(b.id)
        : a.createdAt.localeCompare(b.createdAt),
    );
  });
}

/**
 * Read a single operation by id, or `null` when it has been
 * dequeued. The conflict dialog uses this to refresh its view after
 * the user picks Amend or Discard.
 */
export async function getOperation(id: string): Promise<SyncQueueOperation | null> {
  return withStore('readonly', async (store) => {
    const result = await awaitRequest(store.get(id));
    return (result as SyncQueueOperation | undefined) ?? null;
  });
}

/**
 * Apply a failed-attempt update to an operation. Returns the fresh
 * record so the replay loop can decide whether to keep retrying. The
 * function is exported so `./replay.ts` can call it without
 * duplicating IndexedDB plumbing.
 *
 * Returns `null` when the record has been deleted out from under us
 * (for example because the user clicked Discard mid-replay). The
 * caller is expected to treat the absent record as a signal to exit
 * its retry loop.
 */
export async function persistAttempt(
  id: string,
  attemptCount: number,
  lastAttemptAt: string,
  lastError: string,
): Promise<SyncQueueOperation | null> {
  return withStore('readwrite', async (store) => {
    const existing = (await awaitRequest(store.get(id))) as
      | SyncQueueOperation
      | undefined;
    if (!existing) return null;
    const updated: SyncQueueOperation = {
      ...existing,
      attemptCount,
      lastAttemptAt,
      lastError,
    };
    store.put(updated);
    return updated;
  });
}

// ─── Test seam ───────────────────────────────────────────────────────────────

/**
 * Wipe the entire queue. Exported only for tests and the
 * "Discard all queued operations" admin action. Do NOT call from
 * normal product code — Sync_Queue contents are user data.
 */
export async function _resetForTests(): Promise<void> {
  if (typeof indexedDB === 'undefined') return;
  await new Promise<void>((resolve, reject) => {
    const req = indexedDB.deleteDatabase(DB_NAME);
    req.onsuccess = () => resolve();
    req.onerror = () => reject(req.error ?? new Error('deleteDatabase failed'));
    req.onblocked = () => resolve();
  });
}
