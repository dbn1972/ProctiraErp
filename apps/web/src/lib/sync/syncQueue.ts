/**
 * apps/web/src/lib/sync/syncQueue.ts — Sync_Queue (IndexedDB)
 * (Task 54.2, Requirements 38.5, 38.6, 38.7, Design §I)
 * =====================================================================
 *
 * The Sync_Queue is the single source of truth for write operations
 * the Frontend_Shell could not deliver to the API_Gateway because the
 * user was offline. It lives at the application layer (above the
 * service worker, which `bypasses` POST/PUT/PATCH/DELETE — see
 * `apps/web/src/lib/sw/pickStrategy.ts` and `apps/web/public/sw.js`).
 *
 * Module layout:
 *
 *   • This file owns persistence: the IndexedDB schema, opening /
 *     upgrading the database, and the CRUD helpers (`enqueue`,
 *     `dequeue`, `peekAll`, `getOperation`, `persistAttempt`).
 *
 *   • `./replay.ts` owns the drain loop: submission-order iteration,
 *     exponential backoff, idempotency-header injection, and the
 *     pluggable wait/now/abort options.
 *
 *   • `./idempotencyKey.ts` owns UUID v4 generation.
 *
 * Splitting these three concerns makes each unit testable in
 * isolation and keeps `replay.ts` agnostic of the storage backend so
 * a future swap (e.g. WebLocks, OPFS) only touches this file.
 *
 * Persistence design decisions:
 *
 *   • IndexedDB is used directly with a tiny wrapper rather than the
 *     `idb` library. The API surface needed here is small enough that
 *     a hand-rolled wrapper is auditable and avoids a runtime
 *     dependency. Tests use `fake-indexeddb` to drive the same APIs
 *     in Node.
 *
 *   • Database name is namespaced per brand via the `NEXT_PUBLIC_BRAND`
 *     / `NEXT_PUBLIC_BRAND` env (default `proctira`) so multiple branded
 *     apps on the same origin do not collide.
 *
 *   • Operations are stored in a single object store with the field
 *     `createdAt` indexed so replay can iterate in submission order
 *     without sorting in JavaScript.
 *
 *   • The module is SSR-safe. The `openDatabase` helper rejects with
 *     a descriptive error if `indexedDB` is not available, so callers
 *     can guard with `typeof indexedDB !== 'undefined'`.
 */

import { generateIdempotencyKey } from './idempotencyKey';

// ─── Constants ───────────────────────────────────────────────────────────────

/** IndexedDB database name. Namespaced per brand so themed
 * deployments on the same origin do not share storage. The brand
 * default mirrors `<brand>-sync-queue` from Design §I.
 */
const DB_NAME = `${getBrand()}-sync-queue`;

/** Bumped whenever the schema changes. Triggers `onupgradeneeded`. */
const DB_VERSION = 1;

/** Single object store holding all queued operations. */
const STORE_NAME = 'operations';

/** Index on `createdAt` so replay can iterate in submission order. */
const INDEX_CREATED_AT = 'createdAt';

// ─── Public types ────────────────────────────────────────────────────────────

export type SyncOperationType = 'POST' | 'PUT' | 'PATCH' | 'DELETE';

/**
 * Persisted shape of a single queued write operation. Mirrors the 12
 * fields named in task 54.2.
 *
 * The schema intentionally separates the network-level detail
 * (`operationType`, `targetEntity`, `targetId`, `payload`) from the
 * replay-control metadata (`attemptCount`, `lastAttemptAt`,
 * `lastError`) so a future migration can split them into two stores
 * without changing the public types.
 */
export interface SyncQueueOperation {
  /** Stable UUID generated by `enqueue`. Primary key. */
  id: string;
  /** Tenant subdomain / id captured at enqueue time. */
  tenantId: string;
  /** Authenticated user id captured at enqueue time. */
  userId: string;
  /** HTTP verb to replay. */
  operationType: SyncOperationType;
  /** Logical entity (e.g. `attendance`, `student`) — for grouping in UI. */
  targetEntity: string;
  /**
   * Target identifier inside the entity. Use empty string when the
   * operation creates a new record and the id is unknown locally.
   */
  targetId: string;
  /**
   * The full request to replay. Stored as a structured object so
   * IndexedDB can serialise it natively (no JSON.parse on read).
   */
  payload: SyncOperationPayload;
  /** Sent as `Idempotency-Key` on every replay attempt. */
  idempotencyKey: string;
  /** ISO 8601 UTC timestamp of the original submission. Indexed. */
  createdAt: string;
  /** 0 before any replay attempt; bumped per failure. */
  attemptCount: number;
  /** ISO 8601 UTC of the most recent attempt, or null pre-replay. */
  lastAttemptAt: string | null;
  /** Last failure message (status + body excerpt), or null. */
  lastError: string | null;
}

/** The portion of a `fetch()` request that we persist for replay.
 * URL is required; `headers` and `body` are optional but stored
 * verbatim.
 */
export interface SyncOperationPayload {
  url: string;
  headers?: Record<string, string>;
  body?: string | null;
}

/** Input shape for `enqueue`. The id, idempotency key, and replay
 * metadata are filled in by the queue itself; everything else must
 * come from the caller.
 */
export interface EnqueueInput {
  tenantId: string;
  userId: string;
  operationType: SyncOperationType;
  targetEntity: string;
  targetId?: string;
  payload: SyncOperationPayload;
  /** Optional pre-generated UUID (lets callers do optimistic UI). */
  id?: string;
  /** Optional pre-generated idempotency key (defaults to UUID). */
  idempotencyKey?: string;
  /** Override `createdAt` (test seam). Defaults to `new Date().toISOString()`. */
  createdAt?: string;
}

