#!/usr/bin/env node
/**
 * G-804 — Generate docs/testing/PAGE_REGRESSION_MATRIX.md from the App Router
 * page inventory and the Playwright specs that reference each page.
 *
 *   node tools/scripts/page-regression-matrix.mjs            # write the doc
 *   node tools/scripts/page-regression-matrix.mjs --check    # exit 1 if stale
 *
 * The unit gate apps/web/src/app/page-regression-matrix.test.ts enforces the
 * same rule (every page has ≥1 spec); this script is the human-readable view.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const APP_DIR = join(ROOT, 'apps/web/src/app');
const E2E_DIR = join(ROOT, 'apps/web/e2e');
const OUT = join(ROOT, 'docs/testing/PAGE_REGRESSION_MATRIX.md');

function walk(dir, predicate, acc = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, predicate, acc);
    else if (predicate(entry)) acc.push(full);
  }
  return acc;
}

const pages = walk(APP_DIR, (f) => f === 'page.tsx')
  .map((file) => {
    const segments = relative(APP_DIR, dirname(file))
      .split(sep)
      .filter((seg) => seg.length > 0 && !(seg.startsWith('(') && seg.endsWith(')')));
    const group = relative(APP_DIR, dirname(file)).split(sep)[0] ?? '';
    return { route: segments.length ? `/${segments.join('/')}` : '/', group };
  })
  .sort((a, b) => a.route.localeCompare(b.route));

const specs = walk(E2E_DIR, (f) => f.endsWith('.spec.ts')).map((file) => ({
  name: relative(E2E_DIR, file),
  source: readFileSync(file, 'utf8'),
}));

const escapeRegExp = (v) => v.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function matcher(route) {
  const pattern = route
    .split('/')
    .map((seg) => (seg.startsWith('[') && seg.endsWith(']') ? '[^/\'"`?]+' : escapeRegExp(seg)))
    .join('/');
  return new RegExp(`['"\`]${pattern}(?:[?'"\`]|\\$\\{)`);
}

const CATEGORY = [
  [/a11y|axe/i, 'a11y'],
  [/dark-mode/i, 'dark'],
  [/touch-target/i, 'touch'],
  [/visual-regression/i, 'visual'],
  [/rtl/i, 'rtl'],
  [/loading-skeleton/i, 'cls'],
  [
    /write|journey|lms|scholarships|health|workflows|parent|login|attendance|assessment|transfer|bulk/i,
    'functional',
  ],
];
const categorise = (name) => CATEGORY.find(([re]) => re.test(name))?.[1] ?? 'smoke';

const rows = pages.map(({ route, group }) => {
  const re = matcher(route);
  const hits =
    route === '/'
      ? specs.map((s) => s.name)
      : specs.filter((s) => re.test(s.source)).map((s) => s.name);
  const kinds = [...new Set(hits.map(categorise))].sort();
  return { route, group, hits, kinds };
});

const uncovered = rows.filter((r) => r.hits.length === 0);
const byGroup = new Map();
for (const row of rows) {
  const key = row.group || '(root)';
  if (!byGroup.has(key)) byGroup.set(key, []);
  byGroup.get(key).push(row);
}

const lines = [];
lines.push('# Page-wise functional & regression matrix (G-804)');
lines.push('');
lines.push('> Generated by `node tools/scripts/page-regression-matrix.mjs`. Do not edit by hand.');
lines.push(
  '> Gate: `apps/web/src/app/page-regression-matrix.test.ts` fails when any page lacks an e2e reference.',
);
lines.push('');
lines.push(`- App Router pages: **${pages.length}**`);
lines.push(`- Playwright specs: **${specs.length}**`);
lines.push(`- Pages without any e2e reference: **${uncovered.length}**`);
lines.push('');
lines.push(
  'Coverage kinds: `functional` (page-wise functional / write flow), `a11y` (axe WCAG 2.1 AA), `dark`, `touch` (≥44px targets), `rtl`, `cls` (loading skeleton), `visual` (screenshot baseline), `smoke` (inventory / route resolution).',
);
lines.push('');
for (const [group, groupRows] of [...byGroup.entries()].sort()) {
  lines.push(`## ${group}`);
  lines.push('');
  lines.push('| Page | Coverage kinds | Specs |');
  lines.push('|---|---|---|');
  for (const r of groupRows) {
    const specList =
      r.route === '/' ? '_all authenticated specs_' : r.hits.map((h) => `\`${h}\``).join('<br>');
    lines.push(`| \`${r.route}\` | ${r.kinds.join(', ') || '—'} | ${specList || '**none**'} |`);
  }
  lines.push('');
}
const doc = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== doc) {
    console.error(
      `${relative(ROOT, OUT)} is stale — run node tools/scripts/page-regression-matrix.mjs`,
    );
    process.exit(1);
  }
  console.log('page regression matrix up to date');
} else {
  writeFileSync(OUT, doc);
  console.log(
    `wrote ${relative(ROOT, OUT)} (${pages.length} pages, ${uncovered.length} uncovered)`,
  );
}
if (uncovered.length > 0) {
  console.error('Uncovered pages:\n' + uncovered.map((r) => `  ${r.route}`).join('\n'));
  process.exit(1);
}
