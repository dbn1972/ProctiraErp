#!/usr/bin/env node
/**
 * Bundle a Fastify backend entrypoint to compiled ESM for production images.
 *
 * W1-ARCH-09: production containers must boot with `node dist/...`, not `tsx`
 * against TypeScript sources. Workspace packages export `.ts` entrypoints and
 * the base tsconfig is `noEmit`, so a plain `tsc` emit graph is not runnable
 * under Node. This script esbuilds the service entry + `@proctira/*` workspace
 * sources into one ESM file and leaves third-party packages external (resolved
 * from node_modules at runtime, with `backend-runtime-resolve.mjs` as a pnpm
 * fallback for transitive deps).
 *
 * Usage:
 *   node tools/scripts/bundle-backend-runtime.mjs \
 *     --cwd apps/api-gateway \
 *     --entry src/server.ts \
 *     --outfile dist/server.js
 *
 * Local/dev continues to use `tsx` via package `dev` scripts.
 */
import { mkdirSync } from 'node:fs';
import { dirname, isAbsolute, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import * as esbuild from 'esbuild';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../..');

function parseArgs(argv) {
  const out = {
    cwd: process.cwd(),
    entry: 'src/server.ts',
    outfile: 'dist/server.js',
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = argv[i + 1];
    if (arg === '--cwd' && next) {
      out.cwd = next;
      i += 1;
    } else if (arg === '--entry' && next) {
      out.entry = next;
      i += 1;
    } else if (arg === '--outfile' && next) {
      out.outfile = next;
      i += 1;
    } else if (arg === '--help' || arg === '-h') {
      out.help = true;
    } else if (arg.startsWith('-')) {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return out;
}

/**
 * Bundle workspace TypeScript (`@proctira/*` and relative imports).
 * Externalize everything else so Fastify/pg/ioredis/etc. load from node_modules.
 */
function createExternalizeNonWorkspacePlugin() {
  return {
    name: 'externalize-non-workspace',
    setup(build) {
      build.onResolve({ filter: /.*/ }, (args) => {
        // Relative / absolute paths stay in the graph (esbuild resolves them).
        if (args.path.startsWith('.') || isAbsolute(args.path) || args.path.startsWith('/')) {
          return null;
        }
        // Workspace packages ship TypeScript sources — must be bundled.
        if (args.path === '@proctira' || args.path.startsWith('@proctira/')) {
          return null;
        }
        return { path: args.path, external: true };
      });
    },
  };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log(`Usage: node tools/scripts/bundle-backend-runtime.mjs [options]

Options:
  --cwd <dir>       Package directory (default: cwd)
  --entry <file>    TypeScript entry relative to --cwd (default: src/server.ts)
  --outfile <file>  Output JS relative to --cwd (default: dist/server.js)
`);
    process.exit(0);
  }

  const cwd = isAbsolute(args.cwd) ? args.cwd : resolve(process.cwd(), args.cwd);
  const entry = isAbsolute(args.entry) ? args.entry : resolve(cwd, args.entry);
  const outfile = isAbsolute(args.outfile) ? args.outfile : resolve(cwd, args.outfile);

  mkdirSync(dirname(outfile), { recursive: true });

  const result = await esbuild.build({
    absWorkingDir: cwd,
    entryPoints: [entry],
    outfile,
    bundle: true,
    platform: 'node',
    target: 'node20',
    format: 'esm',
    sourcemap: true,
    banner: {
      js: '// Generated by tools/scripts/bundle-backend-runtime.mjs (W1-ARCH-09)\n',
    },
    logLevel: 'info',
    plugins: [createExternalizeNonWorkspacePlugin()],
    mainFields: ['module', 'main'],
    conditions: ['import', 'module', 'default'],
  });

  if (result.errors.length > 0) {
    process.exit(1);
  }

  console.log(
    `bundle-backend-runtime: wrote ${pathToFileURL(outfile).pathname} (repo=${repoRoot})`,
  );
}

main().catch((err) => {
  console.error('bundle-backend-runtime failed:', err);
  process.exit(1);
});
