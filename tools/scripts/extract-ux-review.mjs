#!/usr/bin/env node
/**
 * Regenerates docs/audits/INSTITUTIONS_UX_TRACKER.md from the prototype
 * ux-review JSON plus docs/audits/institutions-ux-status.json.
 *
 *   node tools/scripts/extract-ux-review.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const PROTO = join(ROOT, 'design/prototype/institutions');
const STATUS_PATH = join(ROOT, 'docs/audits/institutions-ux-status.json');
const OUT = join(ROOT, 'docs/audits/INSTITUTIONS_UX_TRACKER.md');

const SCREEN = {
  'list.html': 'List',
  'detail.html': 'Detail',
  'detail-classes.html': 'Classes',
  'detail-curriculum.html': 'Curriculum',
  'detail-edit.html': 'Edit',
  'detail-gradebook.html': 'Gradebook',
  'detail-grades.html': 'Grades',
  'detail-infrastructure.html': 'Infrastructure',
  'detail-overview.html': 'Overview',
  'detail-schedule.html': 'Schedule',
  'detail-schedule-section.html': 'Schedule section',
  'detail-timetable.html': 'Timetable',
  'detail-timetable-generate.html': 'Timetable generate',
  'detail-timetable-substitutions.html': 'Timetable substitutions',
  'new.html': 'New',
};

function extract() {
  const files = readdirSync(PROTO)
    .filter((name) => name.endsWith('.html'))
    .sort();
  const screens = [];
  for (const file of files) {
    const html = readFileSync(join(PROTO, file), 'utf8');
    const match = html.match(/<script[^>]*id="ux-review"[^>]*>([\s\S]*?)<\/script>/);
    if (!match) throw new Error(`No ux-review JSON in ${file}`);
    const data = JSON.parse(match[1]);
    if (!Array.isArray(data.issues)) throw new Error(`No issues array in ${file}`);
    screens.push({
      file,
      screen: SCREEN[file] ?? file,
      route: data.route,
      source: data.source,
      issues: data.issues.map((issue, index) => ({
        id: `${file}#${index + 1}`,
        severity: issue.severity,
        finding: issue.text,
      })),
    });
  }
  return screens;
}

function cell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
}

const screens = extract();
const statusDoc = JSON.parse(readFileSync(STATUS_PATH, 'utf8'));
const byId = new Map((statusDoc.findings ?? []).map((row) => [row.id, row]));
const parity = statusDoc.parity ?? {};

const findings = [];
for (const screen of screens) {
  screen.issues.forEach((issue) => {
    const overlay = byId.get(issue.id);
    if (!overlay) {
      throw new Error(`Missing status overlay for ${issue.id}`);
    }
    findings.push({ ...issue, screen: screen.screen, route: screen.route, ...overlay });
  });
}

const counts = { DONE: 0, IN_PROGRESS: 0, NOT_DONE: 0 };
const byScreen = new Map();
for (const row of findings) {
  counts[row.status] = (counts[row.status] ?? 0) + 1;
  if (!byScreen.has(row.screen)) {
    byScreen.set(row.screen, {
      DONE: 0,
      IN_PROGRESS: 0,
      NOT_DONE: 0,
      PARTIAL: 0,
      route: row.route,
    });
  }
  const bucket = byScreen.get(row.screen);
  bucket[row.status] = (bucket[row.status] ?? 0) + 1;
  if (row.disposition === 'PARTIAL') bucket.PARTIAL += 1;
}

const lines = [];
lines.push('# Institutions UX tracker');
lines.push('');
lines.push(
  'Generated by `node tools/scripts/extract-ux-review.mjs` from `design/prototype/institutions/*.html` (`<script id="ux-review">`) and `docs/audits/institutions-ux-status.json`. Do not edit the table by hand — update the status JSON and regenerate.',
);
lines.push('');
lines.push(`Tip recorded in the status file: \`${statusDoc.tip ?? 'uncommitted'}\`.`);
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push(`- Findings: **${findings.length}** across **${screens.length}** screens.`);
lines.push(
  `- Status: DONE ${counts.DONE ?? 0} · IN_PROGRESS ${counts.IN_PROGRESS ?? 0} · NOT_DONE ${counts.NOT_DONE ?? 0}.`,
);
lines.push('');
lines.push(
  '| Screen | Route | DONE | IN_PROGRESS | NOT_DONE | PARTIAL dispositions | Prototype parity + functional e2e |',
);
lines.push('| --- | --- | ---: | ---: | ---: | ---: | --- |');
for (const screen of screens) {
  const bucket = byScreen.get(screen.screen);
  const note = parity[screen.file] ?? 'Not claimed.';
  lines.push(
    `| ${cell(screen.screen)} | \`${cell(screen.route)}\` | ${bucket.DONE ?? 0} | ${bucket.IN_PROGRESS ?? 0} | ${bucket.NOT_DONE ?? 0} | ${bucket.PARTIAL ?? 0} | ${cell(note)} |`,
  );
}
lines.push('');
lines.push('## Findings');
lines.push('');
lines.push('| Screen | Route | Severity | Finding | Status | Owner PR | Evidence | Disposition |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const row of findings) {
  lines.push(
    `| ${cell(row.screen)} | \`${cell(row.route)}\` | ${cell(row.severity)} | ${cell(row.finding)} | ${cell(row.status)} | ${cell(row.ownerPr)} | ${cell(row.evidence)} | ${cell(row.disposition)} |`,
  );
}
lines.push('');
lines.push('## Disposition rule');
lines.push('');
lines.push(
  'Allowed values only: `FULLY_CLOSED`, `PARTIAL`, `OPEN`, `REGRESSED`, `EXTERNALLY_UNVERIFIED`. A DONE status still needs tip evidence (test name, capture, or commit). Items owned by another open PR stay `IN_PROGRESS` and are not edited here.',
);
lines.push('');

writeFileSync(OUT, lines.join('\n'));
const total = findings.length;
if (total !== 57 || screens.length !== 15) {
  console.error(`Expected 15 screens and 57 findings, got ${screens.length} and ${total}`);
  process.exit(1);
}
console.log(`Wrote ${OUT} (${screens.length} screens, ${total} findings)`);
